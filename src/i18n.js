let current = 'ko';
try {
  current = localStorage.getItem('planner-lang') === 'en' ? 'en' : 'ko';
} catch (e) {
  current = 'ko';
}
document.documentElement.lang = current;

export const getLang = () => current;

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'ko';
  document.documentElement.lang = current;
  try { localStorage.setItem('planner-lang', current); } catch (e) { /* ignore */ }
}

export function tr(text, vars) {
  let out = current === 'en' && EN[text] !== undefined ? EN[text] : text;
  if (vars) {
    for (const k of Object.keys(vars)) out = out.split(`{${k}}`).join(String(vars[k]));
  }
  return out;
}

